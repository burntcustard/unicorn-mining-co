fn fold(value: char) -> u32 {
    let code = u32::from(value);
    let position = SIMPLE_FOLDS.partition_point(|&(start, _, _, _)| start <= code);
    if position > 0 {
        let (start, end, stride, delta) = SIMPLE_FOLDS[position - 1];
        if code <= end && (code - start).is_multiple_of(stride) {
            return code.wrapping_add_signed(delta);
        }
    }
    code
}

/// Match display names using Unicode simple case folding.
pub(super) fn equal_name(left: &str, right: &str) -> bool {
    if left.is_ascii() && right.is_ascii() {
        left.eq_ignore_ascii_case(right)
    } else {
        left.chars().map(fold).eq(right.chars().map(fold))
    }
}

/// Produce the shared representation for indexed display name lookup.
pub(crate) fn name_key(name: &str) -> String {
    name.chars()
        .map(|value| char::from_u32(fold(value)).expect("simple case fold is a Unicode scalar"))
        .collect()
}
