import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { catalogJson, numericConstants } from './server-spec-catalog';

const directory = process.argv[2];

if (!directory) {
  throw new Error('An output directory is required');
}

const constants = Object.entries(numericConstants)
  .map(([name, value]) => {
    const rustName = name
      .replace(/([A-Z])([A-Z][a-z])/g, '$1_$2')
      .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
      .toUpperCase();
    const literal = String(value);

    if (name === 'HullZIndex') {
      return `pub const ${rustName}: i32 = ${literal};`;
    }

    return `pub const ${rustName}: f64 = ${/[.e]/.test(literal) ? literal : `${literal}.0`};`;
  })
  .join('\n');

writeFileSync(join(directory, 'catalog.json'), catalogJson);
writeFileSync(
  join(directory, 'spec_constants.rs'),
  `// Generated by scripts/generate-rust-catalog.ts.\n${constants}\n`,
);
