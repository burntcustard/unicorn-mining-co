import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { catalogJson, numericConstants } from './server-spec-catalog';

const constants = Object.entries(numericConstants)
  .map(([name, value]) => `const ${name} = ${value}`)
  .join('\n');
const digest = createHash('sha256')
  .update(catalogJson)
  .update(constants)
  .digest('hex');
const source = `// Code generated by scripts/generate-go-catalog.ts; DO NOT EDIT.\n// SHA-256: ${digest}\npackage specs\n\nconst catalogJSON = ${JSON.stringify(catalogJson)}\n\n${constants}\n`;

writeFileSync('src/server-go/specs/catalog_gen.go', source);
